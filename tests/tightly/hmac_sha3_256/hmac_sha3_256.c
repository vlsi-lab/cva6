// HMAC-SHA3-256 benchmark. Identical source on the software and tightly
// trees -- only the linked fips202.c/hmac.c dependencies differ, per run.sh.
// Expected output computed independently via Python's hmac module
// (hmac.new(key, msg, hashlib.sha3_256)).

#include "uart.h"
#include "encoding.h"
#include "bench.h"
#include "hmac.h"

static const uint8_t KEY[19] = {
    0x68, 0x6d, 0x61, 0x63, 0x2d, 0x6b, 0x65, 0x79, 0x2d, 0x30, 0x31, 0x32,
    0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39,
};

static const uint8_t MSG[41] = {
    0x48, 0x4d, 0x41, 0x43, 0x20, 0x62, 0x65, 0x6e, 0x63, 0x68, 0x6d, 0x61,
    0x72, 0x6b, 0x20, 0x6d, 0x65, 0x73, 0x73, 0x61, 0x67, 0x65, 0x20, 0x66,
    0x6f, 0x72, 0x20, 0x6b, 0x65, 0x63, 0x63, 0x5f, 0x61, 0x65, 0x73, 0x5f,
    0x6b, 0x5f, 0x78, 0x69, 0x66,
};

static const uint8_t EXPECTED[32] = {
    0x95, 0x18, 0x7e, 0xa9, 0x86, 0x97, 0xc3, 0xa3, 0x50, 0xca, 0x6c, 0x72,
    0xa5, 0x72, 0x33, 0xda, 0x58, 0xf9, 0x21, 0x82, 0x56, 0x42, 0xf0, 0x4f,
    0x7d, 0x59, 0x3a, 0x1f, 0x39, 0xea, 0x7d, 0x6c,
};

int main()
{
  uint8_t out[32];
  int errors = 0;
  unsigned long cycles, instrs;

  printf("HMAC-SHA3-256 Benchmark\n");

  BENCH_ENABLE();
  BENCH_START();
  hmac_sha3_256(out, KEY, sizeof(KEY), MSG, sizeof(MSG));
  BENCH_READ(cycles, instrs);

  printf("cycles=%lu instrs=%lu\n", cycles, instrs);

  for (int i = 0; i < 32; i++) {
    if (out[i] != EXPECTED[i]) {
      printf("!!! Mismatch at byte %d: expected 0x%02x, got 0x%02x !!!\n", i, EXPECTED[i], out[i]);
      errors++;
    }
  }

  if (errors == 0) printf("HMAC-SHA3-256 Benchmark terminated with no errors.\n");
  else              printf("HMAC-SHA3-256 Benchmark terminated with %d errors\n", errors);

  return errors;
}
