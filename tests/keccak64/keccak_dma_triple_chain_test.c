/* independently computed via Python hashlib: SHAKE256(pub)[:16] */
static const uint8_t expected_hpub[16] = {
	0xb7, 0xa1, 0xdb, 0x80, 0x58, 0xcc, 0x2a, 0x4c,
	0x86, 0x7e, 0x0d, 0xb3, 0x67, 0x09, 0xf4, 0x63,
};

int
main(void)
{
	uint8_t got[16];

	printf("Keccak DMA job engine - multi-chain (3-permutation) absorb test\n");
	printf("pub_len=%d, rate=136, blocks=%d, remainder=%d\n",
	    (int)sizeof(pub), (int)(sizeof(pub) / 136), (int)(sizeof(pub) % 136));

	/* single job, hardware autonomously chains 3 permutations internally */
	run_job(pub, sizeof(pub), 1, 0, 0);
	printf("absorb (single job, 450 bytes) done\n");

	/* flip-only job at dptr=42 (450 % 136), matching shake_flip() */
	run_job(0, 0, 0, 1, sizeof(pub) % 136);
	printf("flip done\n");

	/* final permutation, mirroring shake_extract()'s process_block_resident() */
	permute_resident();
	printf("final permute done\n");

	for (int i = 0; i < 25 && i < 2; i++) {
		uint64_t v = cryptoState[i];
		for (int b = 0; b < 8; b++) {
			got[i * 8 + b] = (uint8_t)(v >> (b * 8));
		}
	}

	for (int i = 0; i < 16; i++) {
		if (got[i] != expected_hpub[i]) {
			printf("!!! hpub byte %d mismatch: expected 0x%02x, got 0x%02x !!!\n",
			    i, expected_hpub[i], got[i]);
			errors++;
		}
	}

	if (errors == 0)
		printf("Keccak multi-chain absorb test terminated with no errors.\n");
	else
		printf("Keccak multi-chain absorb test terminated with %d errors\n", errors);

	return 0;
}
