// SHA3-512 benchmark. Identical source on the software and tightly trees --
// only the linked fips202.c (and, on tightly, keccak_permute.s) differs, per
// run.sh. Expected digest computed independently via Python's hashlib.

#include "uart.h"
#include "encoding.h"
#include "bench.h"
#include "fips202.h"

static const uint8_t MSG[43] = {
    0x54, 0x68, 0x65, 0x20, 0x71, 0x75, 0x69, 0x63, 0x6b, 0x20, 0x62, 0x72,
    0x6f, 0x77, 0x6e, 0x20, 0x66, 0x6f, 0x78, 0x20, 0x6a, 0x75, 0x6d, 0x70,
    0x73, 0x20, 0x6f, 0x76, 0x65, 0x72, 0x20, 0x74, 0x68, 0x65, 0x20, 0x6c,
    0x61, 0x7a, 0x79, 0x20, 0x64, 0x6f, 0x67,
};

static const uint8_t EXPECTED[64] = {
    0x01, 0xde, 0xdd, 0x5d, 0xe4, 0xef, 0x14, 0x64, 0x24, 0x45, 0xba, 0x5f,
    0x5b, 0x97, 0xc1, 0x5e, 0x47, 0xb9, 0xad, 0x93, 0x13, 0x26, 0xe4, 0xb0,
    0x72, 0x7c, 0xd9, 0x4c, 0xef, 0xc4, 0x4f, 0xff, 0x23, 0xf0, 0x7b, 0xf5,
    0x43, 0x13, 0x99, 0x39, 0xb4, 0x91, 0x28, 0xca, 0xf4, 0x36, 0xdc, 0x1b,
    0xde, 0xe5, 0x4f, 0xcb, 0x24, 0x02, 0x3a, 0x08, 0xd9, 0x40, 0x3f, 0x9b,
    0x4b, 0xf0, 0xd4, 0x50,
};

int main()
{
  uint8_t digest[64];
  int errors = 0;
  unsigned long cycles, instrs;

  printf("SHA3-512 Benchmark\n");

  BENCH_ENABLE();
  BENCH_START();
  sha3_512(digest, MSG, sizeof(MSG));
  BENCH_READ(cycles, instrs);

  printf("cycles=%lu instrs=%lu\n", cycles, instrs);

  for (int i = 0; i < 64; i++) {
    if (digest[i] != EXPECTED[i]) {
      printf("!!! Mismatch at byte %d: expected 0x%02x, got 0x%02x !!!\n", i, EXPECTED[i], digest[i]);
      errors++;
    }
  }

  if (errors == 0) printf("SHA3-512 Benchmark terminated with no errors.\n");
  else              printf("SHA3-512 Benchmark terminated with %d errors\n", errors);

  return errors;
}
