// KMAC256 benchmark. Identical source on the software and tightly trees --
// only the linked fips202.c/kmac.c dependencies differ, per run.sh. Expected
// output computed independently via Python's pycryptodome (Crypto.Hash.KMAC256).

#include "uart.h"
#include "encoding.h"
#include "bench.h"
#include "kmac.h"

static const uint8_t KEY[32] = {
    0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b,
    0x0c, 0x0d, 0x0e, 0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
    0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f,
};

static const uint8_t MSG[41] = {
    0x4b, 0x4d, 0x41, 0x43, 0x20, 0x62, 0x65, 0x6e, 0x63, 0x68, 0x6d, 0x61,
    0x72, 0x6b, 0x20, 0x6d, 0x65, 0x73, 0x73, 0x61, 0x67, 0x65, 0x20, 0x66,
    0x6f, 0x72, 0x20, 0x6b, 0x65, 0x63, 0x63, 0x5f, 0x61, 0x65, 0x73, 0x5f,
    0x6b, 0x5f, 0x78, 0x69, 0x66,
};

static const uint8_t CUSTOM[8] = {
    0x4d, 0x79, 0x43, 0x75, 0x73, 0x74, 0x6f, 0x6d,
};

static const uint8_t EXPECTED[32] = {
    0xa9, 0x0e, 0x14, 0xae, 0x6f, 0x9a, 0x62, 0x7c, 0x62, 0xfd, 0x75, 0x44,
    0x62, 0xd9, 0x84, 0x71, 0x28, 0x40, 0x40, 0xc7, 0x9a, 0x4e, 0x75, 0x22,
    0xc7, 0x1f, 0x65, 0x51, 0x1a, 0xbc, 0x80, 0x7d,
};

int main()
{
  uint8_t out[32];
  int errors = 0;
  unsigned long cycles, instrs;

  printf("KMAC256 Benchmark\n");

  BENCH_ENABLE();
  BENCH_START();
  kmac256(out, sizeof(out), KEY, sizeof(KEY), MSG, sizeof(MSG), CUSTOM, sizeof(CUSTOM));
  BENCH_READ(cycles, instrs);

  printf("cycles=%lu instrs=%lu\n", cycles, instrs);

  for (int i = 0; i < 32; i++) {
    if (out[i] != EXPECTED[i]) {
      printf("!!! Mismatch at byte %d: expected 0x%02x, got 0x%02x !!!\n", i, EXPECTED[i], out[i]);
      errors++;
    }
  }

  if (errors == 0) printf("KMAC256 Benchmark terminated with no errors.\n");
  else              printf("KMAC256 Benchmark terminated with %d errors\n", errors);

  return errors;
}
