/*
 * Multi-rate-block squeeze correctness test for the Phase 1 DMA absorb
 * driver (shake_init/shake_inject/shake_flip/shake_extract in sha3.c).
 *
 * Every existing register-level and software-level test to date only ever
 * squeezes <= 96 bytes of output, which is less than one SHAKE256 rate
 * block (136 bytes) -- so shake_extract()'s chained-squeeze branch
 * (dptr == rate -> keccak_hw_upload_resident() + process_block_resident(),
 * the CSREG-triggered legacy permute path used only during squeeze, never
 * during absorb) has never actually been exercised on real hardware. HAWK's
 * own KeyGen squeezes 512 bytes per SHAKE256 context (see ng_hawk.c), which
 * does cross that boundary repeatedly. This test isolates exactly that: one
 * context, one absorb, then a squeeze spanning three rate blocks, checked
 * against an independently computed SHAKE256 digest (Python hashlib).
 *
 * Links only sha3.c (plus bare-metal startup), same as
 * keccak_interleave_test.c.
 */

#include <stddef.h>
