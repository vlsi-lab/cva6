int
main(void)
{
	static uint8_t msg[41];
	static uint8_t out[300];
	shake_context sc;
	int errors = 0;

	for (int i = 0; i < 41; i++) msg[i] = msg_byte(i);

	print_uart("Keccak DMA driver - multi-block squeeze test\n");

	shake_init(&sc, 256);
	shake_inject(&sc, msg, sizeof msg);
	print_uart("inject done\n");
	shake_flip(&sc);
	print_uart("flip done\n");

	/*
	 * Squeeze in three uneven calls (100 + 150 + 50 = 300 bytes) rather
	 * than one call, to also exercise shake_extract() re-entering the
	 * chained-squeeze branch mid-context across separate calls, matching
	 * how ng_hawk.c actually drives it (repeated small shake_extract()
	 * calls against the same context).
	 */
	shake_extract(&sc, out,       100);
	print_uart("extract 1 done\n");
	shake_extract(&sc, out + 100, 150);
	print_uart("extract 2 done\n");
	shake_extract(&sc, out + 250, 50);
	print_uart("extract 3 done\n");

	for (int i = 0; i < 300; i++) {
		if (out[i] != expected[i]) {
			print_uart("!!! byte ");
			print_uart_dec(i);
			print_uart(" mismatch: expected 0x");
			print_uart_byte(expected[i]);
			print_uart(", got 0x");
			print_uart_byte(out[i]);
			print_uart(" !!!\n");
			errors++;
		}
	}

	if (errors == 0) {
		print_uart("Keccak multi-block squeeze test terminated with no errors.\n");
	} else {
		print_uart("Keccak multi-block squeeze test terminated with ");
		print_uart_dec(errors);
		print_uart(" errors\n");
	}

	return 0;
}
